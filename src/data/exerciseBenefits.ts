/**
 * Obtiene los beneficios científicos para un ejercicio.
 * Si no está definido de forma específica, utiliza los beneficios del grupo muscular como fallback dinámico.
 */
export const getExerciseBenefits = (exerciseName: string, muscleGroup: string): string[] => {
  if (!exerciseName) return ["Estímulo biomecánico de alta calidad.", "Promueve el desarrollo y la hipertrofia muscular.", "Aumenta la fuerza y coordinación muscular."];
  
  // 1. Intento de coincidencia exacta en el diccionario
  if (EXERCISES_BENEFITS[exerciseName]) {
    return EXERCISES_BENEFITS[exerciseName];
  }

  // 2. Intento de coincidencia buscando ignorando mayúsculas y acentos
  const normalizedSearch = exerciseName.toLowerCase().normalize("NFD").replace(/[\u0300-\u036f]/g, "");
  const foundKey = Object.keys(EXERCISES_BENEFITS).find(key => {
    return key.toLowerCase().normalize("NFD").replace(/[\u0300-\u036f]/g, "") === normalizedSearch;
  });

  if (foundKey && EXERCISES_BENEFITS[foundKey]) {
    return EXERCISES_BENEFITS[foundKey];
  }

  // 2.5. Intento de coincidencia parcial (si contiene o es contenido por alguna clave del diccionario)
  const foundKeyPartial = Object.keys(EXERCISES_BENEFITS).find(key => {
    const normKey = key.toLowerCase().normalize("NFD").replace(/[\u0300-\u036f]/g, "");
    return normalizedSearch.includes(normKey) || normKey.includes(normalizedSearch);
  });

  if (foundKeyPartial && EXERCISES_BENEFITS[foundKeyPartial]) {
    return EXERCISES_BENEFITS[foundKeyPartial];
  }

  // 3. Fallback basado en el grupo muscular
  const normalizedGroup = (muscleGroup || "").toUpperCase().normalize("NFD").replace(/[\u0300-\u036f]/g, "");
  if (MUSCLE_GROUP_FALLBACKS[normalizedGroup]) {
    return MUSCLE_GROUP_FALLBACKS[normalizedGroup];
  }

  // 4. Fallback genérico absoluto
  return [
    `Optimiza el reclutamiento de fibras en el ejercicio de ${exerciseName}.`,
    "Estimula la hipertrofia muscular y la ganancia de fuerza funcional en el patrón de movimiento.",
    "Mejora la conexión mente-músculo y la estabilidad de las articulaciones involucradas."
  ];
};
